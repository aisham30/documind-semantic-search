"""Citation validation module to verify LLM citations against retrieved chunks."""

import re
from typing import Any, Dict, List, Optional, Set, Tuple
from app.generation.prompts import INSUFFICIENT_EVIDENCE_PHRASE

# Regular expressions to extract citations in various formats
DOC_PAGE_PATTERN = re.compile(
    r"\[Doc:\s*([^,\]]+?),\s*Page:\s*([^,\]]+?)(?:,\s*Chunk:\s*([^,\]]+?))?\]", re.IGNORECASE
)
DOC_CHUNK_PAGE_PATTERN = re.compile(
    r"\[Doc:\s*([^,\]]+?),\s*Chunk:\s*([^,\]]+?),\s*Page:\s*([^,\]]+?)\]", re.IGNORECASE
)
CHUNK_PATTERN = re.compile(r"\[Chunk:\s*([^\]]+?)\]", re.IGNORECASE)

# Keywords indicating that the LLM concluded evidence was insufficient
INSUFFICIENT_KEYWORDS = [
    "insufficient evidence",
    "do not have sufficient evidence",
    "not enough information",
    "cannot answer based on the provided",
    "not mentioned in the provided",
    "no information provided",
    "provided documents do not mention",
    "no evidence",
]


def detect_insufficient_evidence(text: str) -> bool:
    """Check if the response indicates insufficient evidence to answer."""
    if not text:
        return True

    lowered = text.strip().lower()
    if INSUFFICIENT_EVIDENCE_PHRASE.lower() in lowered:
        return True

    # If the response contains citations, it is an answer (or partial answer), not a full refusal
    if "[" in text and (
        DOC_PAGE_PATTERN.search(text)
        or CHUNK_PATTERN.search(text)
        or DOC_CHUNK_PAGE_PATTERN.search(text)
    ):
        return False

    for keyword in INSUFFICIENT_KEYWORDS:
        if keyword in lowered:
            return True

    return False


def normalize_str(val: Any) -> str:
    """Helper to convert any value to a normalized lowercase string."""
    if val is None:
        return ""
    return str(val).strip().lower()


def validate_citations(
    raw_answer: str,
    retrieved_chunks: List[Dict[str, Any]],
) -> Dict[str, Any]:
    """
    Validate citations present in the LLM's raw answer against the retrieved chunks.

    The LLM cannot be trusted to invent document names, chunk IDs, or page numbers.
    Any citation not present in `retrieved_chunks` is discarded.

    Parameters:
        raw_answer: The text generated by the LLM.
        retrieved_chunks: The original list of chunks provided in the prompt.
            Each chunk dict should contain:
            - document_id (str | int)
            - chunk_id (str | int)
            - page_number (int | str | None)
            - text (str)

    Returns:
        dict with keys:
            - answer (str): Cleaned answer text.
            - sources (list[dict]): Validated unique sources with keys:
                "document_id", "chunk_id", "page_number".
            - insufficient_evidence (bool): True if evidence was lacking.
    """
    if not raw_answer or not raw_answer.strip():
        return {
            "answer": "No answer could be generated.",
            "sources": [],
            "insufficient_evidence": True,
            "status": "Insufficient Evidence",
        }

    clean_answer = raw_answer.strip()
    is_insufficient = detect_insufficient_evidence(clean_answer)

    # If the LLM has stated insufficient evidence, no sources should be credited
    if is_insufficient:
        return {
            "answer": clean_answer,
            "sources": [],
            "insufficient_evidence": True,
            "status": "Insufficient Evidence",
        }

    # Index the retrieved chunks for rapid, reliable lookup
    # 1. By (document_id, page_number)
    # 2. By chunk_id
    valid_doc_page_map: Dict[Tuple[str, str], Dict[str, Any]] = {}
    valid_doc_only_map: Dict[str, Dict[str, Any]] = {}
    valid_chunk_map: Dict[str, Dict[str, Any]] = {}

    for chunk in retrieved_chunks:
        doc_id = chunk.get("document_id")
        chunk_id = chunk.get("chunk_id")
        page_num = chunk.get("page_number")

        norm_doc = normalize_str(doc_id)
        norm_chunk = normalize_str(chunk_id)
        norm_page = normalize_str(page_num)

        chunk_record = {
            "document_id": doc_id,
            "chunk_id": chunk_id,
            "page_number": page_num,
        }

        if norm_doc:
            valid_doc_only_map[norm_doc] = chunk_record
            if norm_page:
                valid_doc_page_map[(norm_doc, norm_page)] = chunk_record

        if norm_chunk:
            valid_chunk_map[norm_chunk] = chunk_record

    validated_sources: List[Dict[str, Any]] = []
    seen_sources: Set[Tuple[Any, Any, Any]] = set()

    def add_source(record: Dict[str, Any]):
        key = (record["document_id"], record["chunk_id"], record["page_number"])
        if key not in seen_sources:
            seen_sources.add(key)
            validated_sources.append(record)

    # 1. Match [Doc: ..., Page: ...] or [Doc: ..., Page: ..., Chunk: ...]
    for match in DOC_PAGE_PATTERN.finditer(clean_answer):
        cited_doc = normalize_str(match.group(1))
        cited_page = normalize_str(match.group(2))
        cited_chunk = normalize_str(match.group(3)) if match.lastindex and match.lastindex >= 3 else None

        # Check exact (doc, page) match
        if (cited_doc, cited_page) in valid_doc_page_map:
            add_source(valid_doc_page_map[(cited_doc, cited_page)])
        elif cited_chunk and cited_chunk in valid_chunk_map:
            add_source(valid_chunk_map[cited_chunk])
        # Check if doc exists and page is "n/a" or unknown
        elif cited_doc in valid_doc_only_map and cited_page in {"n/a", "none", ""}:
            add_source(valid_doc_only_map[cited_doc])

    # 2. Match [Doc: ..., Chunk: ..., Page: ...]
    for match in DOC_CHUNK_PAGE_PATTERN.finditer(clean_answer):
        cited_doc = normalize_str(match.group(1))
        cited_chunk = normalize_str(match.group(2))
        cited_page = normalize_str(match.group(3))

        if (cited_doc, cited_page) in valid_doc_page_map:
            add_source(valid_doc_page_map[(cited_doc, cited_page)])
        elif cited_chunk in valid_chunk_map:
            add_source(valid_chunk_map[cited_chunk])

    # 3. Match [Chunk: ...]
    for match in CHUNK_PATTERN.finditer(clean_answer):
        cited_chunk = normalize_str(match.group(1))
        if cited_chunk in valid_chunk_map:
            add_source(valid_chunk_map[cited_chunk])

    return {
        "answer": clean_answer,
        "sources": validated_sources,
        "insufficient_evidence": False,
        "status": "Answer Grounded with Verified Citations",
    }
